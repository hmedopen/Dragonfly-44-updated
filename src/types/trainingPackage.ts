/**
 * Dragonfly 44 - Training Package V1 Specification
 * Canonical schema for Agent Integration handoff, package import/export,
 * and ground-truth validation.
 */

import type { TrainingTaskType, VisualAnnotationRelation } from './training';

export interface TrainingPackageAnnotationV1 {
  id?: string;
  physicalObjectId: string;
  box_2d: [number, number, number, number]; // [ymin, xmin, ymax, xmax] 0-1000
  label: 'balloon' | 'tail' | 'text_region' | 'sfx' | 'panel' | 'character' | 'other';
  translationUnitId?: string;
  readingOrderIndex?: number;
  relationships?: VisualAnnotationRelation[];
  notes?: string;
  isVerified?: boolean; // Set to false when generated by AI/agent
  confidence?: number;
}

export interface TrainingPackageExampleV1 {
  id?: string;
  orderIndex: number;
  title: string;
  sourceFileName?: string;
  imageBase64?: string; // Optional embedded base64 image data (e.g. data:image/png;base64,...)
  imageBlobKey?: string; // Reference to existing blobKey if within same system
  sourceFilePath?: string;
  aiNote: string;
  expectedBehaviour?: string;
  tags?: string[];
  isEnabled?: boolean;
  annotations?: TrainingPackageAnnotationV1[];
}

export interface TrainingPackageManifestV1 {
  schemaVersion: 'dragonfly.training.v1';
  exportedAt: number;
  generator: string; // e.g. "dragonfly-agent" or "dragonfly-training-studio"
  referenceSet: {
    id?: string;
    title: string;
    description: string;
    generalInstructions: string;
    targetTasks: TrainingTaskType[];
    priority?: number;
    enabled?: boolean;
  };
  examples: TrainingPackageExampleV1[];
}

export interface PackageValidationResult {
  isValid: boolean;
  schemaVersion: string;
  errors: string[];
  warnings: string[];
  stats: {
    exampleCount: number;
    annotationCount: number;
    unverifiedAnnotationCount: number;
    embeddedImagesCount: number;
    tasksCount: number;
  };
}
